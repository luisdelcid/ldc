<?php

if(!class_exists('LDC_Installer')){
	final class LDC_Installer {

		// ---------------------------------------------------------------------
        //
		// Public static
        //
		// ---------------------------------------------------------------------

        /**
         * @return void
         */
        public static function install(){
            if(!defined('WPMU_PLUGIN_DIR') || !wp_mkdir_p(WPMU_PLUGIN_DIR)){
                return;
            }
            $content = <<<EOF
<?php
/*
 * Plugin Name: LDC Must-Use
 * Plugin URI: https://luisdelcid.com
 * Description: This is automatically generated by the LDC plugin, and it is automatically disabled when disabling the main plugin.
 * Version: 1.0.0
 * Author: Luis del Cid
 * Author URI: https://luisdelcid.com
 * License: GPL v2 or later
 * License URI: https://www.gnu.org/licenses/gpl-2.0.html
 */

if(defined('ABSPATH')){
	if(in_array('ldc/ldc.php', get_option('active_plugins', [])) || in_array('ldc/ldc.php', array_keys(get_site_option('active_sitewide_plugins', [])))){
		if(file_exists(WP_PLUGIN_DIR . '/ldc/load.php')){
			include_once WP_PLUGIN_DIR . '/ldc/load.php';
		}
	}
}

EOF;
            $file = WPMU_PLUGIN_DIR . '/ldc-must-use.php';
            if(file_exists($file) && md5_file($file) === md5($content)){
                return;
            }
            if(file_put_contents($file, $content) === false){
                add_action('admin_notices', function(){
                    echo '<div class="notice notice-error is-dismissible"><p>LDC Must-Use installation failed.</p></div>';
                });
            }
        }

		// ---------------------------------------------------------------------

    }
}
